// ---- Rendering ---------------------------------------------------------------
function expandRows(rows, w) {
  return rows.map(r => r.length === w ? r : (r.length === w / 2 ? r + [...r].reverse().join('') : r));
}
function spriteRows(key) {
  if (CHARS[key]) return expandRows(CHARS[key].rows, 16);
  if (ICONS[key]) return expandRows(ICONS[key], 12);
  return null;
}
const _sprCache = {};
function sprURL(key, fill) {
  if (typeof key === 'string' && typeof ICON_ALIAS !== 'undefined' && ICON_ALIAS[key] && !fill) return sprURL(ICON_ALIAS[key][0], ICON_ALIAS[key][1]);
  const ck = key + (fill ? JSON.stringify(fill) : '');
  if (_sprCache[ck]) return _sprCache[ck];
  const rows = typeof key === 'string' ? spriteRows(key) : key;
  if (!rows) return '';
  const h = rows.length, w = Math.max(...rows.map(r => r.length));
  const size = Math.max(w, h);
  const c = document.createElement('canvas');
  c.width = size; c.height = size;
  const x = c.getContext('2d');
  const ox = Math.floor((size - w) / 2), oy = Math.floor((size - h) / 2);
  rows.forEach((row, j) => [...row].forEach((ch, i) => {
    if (ch === '.' || ch === ' ') return;
    x.fillStyle = (fill && fill[ch]) || PAL[ch] || '#f0f';
    x.fillRect(ox + i, oy + j, 1, 1);
  }));
  return (_sprCache[ck] = c.toDataURL());
}

// The bomb is drawn procedurally so its body can flash between colours.
function bombRows(lit) {
  const W = 24, H = 24, cx = 11.5, cy = 14, R = 8.6;
  const g = Array.from({ length: H }, () => Array(W).fill('.'));
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const d = Math.hypot(x + 0.5 - cx - 0.5, y + 0.5 - cy - 0.5);
    if (d <= R) g[y][x] = d > R - 1.15 ? 'k' : (lit ? 'r' : 'G');
  }
  // shine
  for (const [x, y] of [[7, 9], [8, 9], [6, 10], [7, 10], [6, 11], [6, 12], [9, 8]]) g[y][x] = lit ? 'm' : 'g';
  if (lit) for (const [x, y] of [[5, 15], [6, 17], [16, 18], [17, 16], [13, 20]]) g[y][x] = 'R';
  // cap
  for (let y = 3; y <= 6; y++) for (let x = 14; x <= 18; x++) {
    const edge = y === 3 || y === 6 || x === 14 || x === 18;
    g[y][x] = edge ? 'k' : 'g';
  }
  // fuse
  for (const [x, y] of [[17, 2], [18, 1], [19, 1], [20, 1], [21, 2]]) g[y][x] = 'T';
  return g.map(r => r.join(''));
}
