// Adds a 1px ink outline around every coloured pixel (for thin shapes).
function outlined(rows) {
  const g = rows.map(r => [...r]);
  const at = (x, y) => (g[y] && g[y][x]) || '.';
  return g.map((row, y) => row.map((ch, x) => {
    if (ch !== '.') return ch;
    const near = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => { const c = at(x + dx, y + dy); return c !== '.' && c !== 'k'; });
    return near ? 'k' : '.';
  }).join(''));
}
