'use strict';
// Builds the single, self-contained fun-party-games.html from src/.
//   node build.js
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'src');
const read = f => fs.readFileSync(path.join(SRC, f), 'utf8');

const fonts = [
  ['Press Start 2P', 'PressStart2P.woff2', '400'],
  ['Pixelify Sans', 'PixelifySans.woff2', '400 700'],
].map(([family, file, weight]) =>
  `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;` +
  `src:url(data:font/woff2;base64,${fs.readFileSync(path.join(SRC, 'fonts', file)).toString('base64')}) format('woff2');}`
).join('\n') +
  // Pixelify Sans draws 2 and 5 like S and 8, so numbers (and $ +) use Press Start 2P,
  // scaled down to sit nicely in body text.
  `\n@font-face{font-family:'PFG Digits';font-style:normal;font-weight:400 700;font-display:swap;size-adjust:64%;` +
  `unicode-range:U+0024,U+002B,U+0030-0039;` +
  `src:url(data:font/woff2;base64,${fs.readFileSync(path.join(SRC, 'fonts', 'PressStart2P.woff2')).toString('base64')}) format('woff2');}`;

// Favicon: the lit bomb sprite, as crisp SVG rects.
const art = new Function(read('art.js') + '\nreturn { PAL, bombRows };')();
const rects = [];
art.bombRows(true).forEach((row, y) => [...row].forEach((ch, x) => {
  if (ch !== '.') rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${art.PAL[ch]}"/>`);
}));
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" shape-rendering="crispEdges">${rects.join('')}</svg>`;

const js = ['art.js', 'art-more.js', 'data.js', 'app.js'].map(read).join('\n');
if (/<\/script/i.test(js)) throw new Error('JS contains "</script" and would break the inline <script>');

const html = read('index.html')
  .replace('/*FAVICON*/', () => 'data:image/svg+xml,' + encodeURIComponent(favicon))
  .replace('/*FONTS*/', () => fonts)
  .replace('/*CSS*/', () => read('style.css'))
  .replace('/*JS*/', () => js);

fs.writeFileSync(path.join(__dirname, 'fun-party-games.html'), html);
// The folder URL (…/fun-party-games/) serves the game directly, with no redirect page.
fs.writeFileSync(path.join(__dirname, 'index.html'), html);

// Installable, offline web app: manifest + a service worker that caches the
// game. The cache name carries a hash of the build so updates reach phones.
const crypto = require('crypto');
const version = crypto.createHash('sha1').update(html).digest('hex').slice(0, 10);
const manifest = {
  name: 'Fun Party Games',
  short_name: 'Party Games',
  start_url: './',
  scope: './',
  display: 'standalone',
  orientation: 'portrait',
  background_color: '#fff3e2',
  theme_color: '#ffe8f2',
  icons: [192, 512].map(n => ({ src: `icons/icon-${n}.png`, sizes: `${n}x${n}`, type: 'image/png' })),
};
fs.writeFileSync(path.join(__dirname, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(__dirname, 'sw.js'), `// Generated by build.js: keeps Fun Party Games working offline.
// Pages: network first (gives up after 4s), then the saved copy.
// Icons and manifest: saved copy first. Nothing here can leave a page hanging.
const CACHE = 'fpg-${version}';
const FILES = ['./', './index.html', './fun-party-games.html', './manifest.webmanifest',
  './icons/icon-180.png', './icons/icon-192.png', './icons/icon-512.png'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE)
    .then(c => c.addAll(FILES.map(f => new Request(f, { cache: 'reload' }))))
    .then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Safari refuses a page response that went through a redirect, so hand back a clean copy.
function clean(res) {
  if (!res || !res.redirected) return res;
  return res.blob().then(body => new Response(body, { status: res.status, statusText: res.statusText, headers: res.headers }));
}
function withTimeout(p, ms) {
  return new Promise((resolve, reject) => {
    const t = setTimeout(() => reject(new Error('timeout')), ms);
    p.then(v => { clearTimeout(t); resolve(v); }, err => { clearTimeout(t); reject(err); });
  });
}

self.addEventListener('fetch', e => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin) return;
  if (url.search.indexOf('reset') !== -1) return;          // ?reset always goes to the network
  const isPage = req.mode === 'navigate' || (req.headers.get('accept') || '').indexOf('text/html') !== -1;

  if (isPage) {
    e.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const net = fetch(url.href, { credentials: 'same-origin', cache: 'no-cache' }).then(clean).then(res => {
        if (res.ok) cache.put(url.pathname.endsWith('/') ? './' : url.pathname, res.clone()).catch(() => {});
        return res;
      });
      try {
        return await withTimeout(net, 4000);
      } catch (err) {
        const hit = (await cache.match(req, { ignoreSearch: true })) || (await cache.match('./'));
        return hit || Response.error();
      }
    })());
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
`);
console.log(`manifest.webmanifest + sw.js written (cache fpg-${version})`);
console.log(`fun-party-games.html written (${(html.length / 1024).toFixed(0)} KB)`);
